'use client';

import Link from 'next/link';
import { usePathname } from 'next/navigation';

const NAV = [
  { href: '/',            label: 'Home',     icon: HomeIcon },
  { href: '/learn',       label: 'Learn',    icon: BookIcon },
  { href: '/flashcards',  label: 'Cards',    icon: CardIcon },
  { href: '/practice',    label: 'Practice', icon: PenIcon  },
  { href: '/add-lesson',  label: 'Add',      icon: PlusIcon },
] as const;

export function BottomNav() {
  const pathname = usePathname();

  return (
    <nav className="fixed bottom-0 left-0 right-0 z-50 bg-card border-t border-rule pb-safe">
      <div className="flex max-w-lg mx-auto">
        {NAV.map(({ href, label, icon: Icon }) => {
          const active = href === '/' ? pathname === '/' : pathname.startsWith(href);
          return (
            <Link
              key={href}
              href={href}
              className={`flex flex-1 flex-col items-center gap-1 py-2.5 text-[11px] font-sans font-medium tracking-wide transition-colors duration-150 ${
                active ? 'text-accent' : 'text-ink-2 hover:text-ink'
              }`}
            >
              <Icon className="w-4.5 h-4.5" />
              {label}
            </Link>
          );
        })}
      </div>
    </nav>
  );
}

